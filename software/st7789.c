/* ── SPI helpers ───────────────────────────────────────────────── */
static void spi_write(const uint8_t *data, int len)
{
    while (len > 0) {
        int n = len > 4096 ? 4096 : len;
        write(spi_fd, data, n);
        data += n;
        len -= n;
    }
}

static void tft_cmd(uint8_t c)
{
    gpio_write(pin_dc, 0);
    write(spi_fd, &c, 1);
}

static void tft_data(const uint8_t *d, int len)
{
    gpio_write(pin_dc, 1);
    spi_write(d, len);
}

static void tft_cmd_d(uint8_t c, const uint8_t *d, int len)
{
    tft_cmd(c);
    if (len > 0) tft_data(d, len);
}

/* ── Public API ────────────────────────────────────────────────── */

int st7789_init(const char *spi_device, int dc_pin, int rst_pin)
{
    pin_dc = dc_pin;
    pin_rst = rst_pin;

    /* Setup GPIO pins */
    gpio_set_output(pin_dc);
    gpio_set_output(pin_rst);

    /* Open SPI */
    spi_fd = open(spi_device, O_RDWR);
    if (spi_fd < 0) {
        perror("st7789: open spidev");
        return -1;
    }
    uint8_t mode = SPI_MODE_0;
    uint32_t speed = 40000000;
    uint8_t bits = 8;
    ioctl(spi_fd, SPI_IOC_WR_MODE, &mode);
    ioctl(spi_fd, SPI_IOC_WR_MAX_SPEED_HZ, &speed);
    ioctl(spi_fd, SPI_IOC_WR_BITS_PER_WORD, &bits);

    /* Hardware reset */
    gpio_write(pin_rst, 1); usleep(100000);
    gpio_write(pin_rst, 0); usleep(100000);
    gpio_write(pin_rst, 1); usleep(200000);

    /* Init sequence (from working test_all_hw.c) */
    tft_cmd(0x01); usleep(200000);  /* SW reset */
    tft_cmd(0x11); usleep(200000);  /* sleep out */

    uint8_t porch[] = {0x0C,0x0C,0x00,0x33,0x33};
    tft_cmd_d(0xB2, porch, 5);
    tft_cmd_d(0xB7, (uint8_t[]){0x35}, 1);
    tft_cmd_d(0xBB, (uint8_t[]){0x19}, 1);
    tft_cmd_d(0xC0, (uint8_t[]){0x2C}, 1);
    tft_cmd_d(0xC2, (uint8_t[]){0x01}, 1);
    tft_cmd_d(0xC3, (uint8_t[]){0x12}, 1);
    tft_cmd_d(0xC4, (uint8_t[]){0x20}, 1);
    tft_cmd_d(0xC6, (uint8_t[]){0x0F}, 1);
    tft_cmd_d(0xD0, (uint8_t[]){0xA4,0xA1}, 2);

    uint8_t pgam[] = {0xD0,0x04,0x0D,0x11,0x13,0x2B,0x3F,0x54,
                      0x4C,0x18,0x0D,0x0B,0x1F,0x23};
    tft_cmd_d(0xE0, pgam, 14);
    uint8_t ngam[] = {0xD0,0x04,0x0C,0x11,0x13,0x2C,0x3F,0x44,
                      0x51,0x2F,0x1F,0x1F,0x20,0x23};
    tft_cmd_d(0xE1, ngam, 14);

    tft_cmd_d(0x3A, (uint8_t[]){0x05}, 1);  /* 16-bit color */
    tft_cmd_d(0x36, (uint8_t[]){0x60}, 1);  /* MADCTL: 90° CW */
    tft_cmd(0x21);                            /* inversion on */
    tft_cmd(0x13);                            /* normal mode */
    tft_cmd(0x29);                            /* display on */
    usleep(100000);

    st7789_clear(COLOR_BLACK);
    st7789_flush();

    fprintf(stderr, "ST7789 TFT initialized on %s (DC=%d, RST=%d)\n",
            spi_device, dc_pin, rst_pin);
    return 0;
}

void st7789_close(void)
{
    if (spi_fd >= 0) {
        st7789_clear(COLOR_BLACK);
        st7789_flush();
        close(spi_fd);
        spi_fd = -1;
    }
}

void st7789_clear(uint16_t color)
{
    for (int i = 0; i < ST7789_WIDTH * ST7789_HEIGHT; i++)
        framebuffer[i] = color;
}

void st7789_pixel(int x, int y, uint16_t color)
{
    if (x >= 0 && x < ST7789_WIDTH && y >= 0 && y < ST7789_HEIGHT)
        framebuffer[y * ST7789_WIDTH + x] = color;
}

void st7789_hline(int x, int y, int w, uint16_t color)
{
    if (y < 0 || y >= ST7789_HEIGHT) return;
    int x1 = x + w - 1;
    if (x < 0) x = 0;
    if (x1 >= ST7789_WIDTH) x1 = ST7789_WIDTH - 1;
    for (int i = x; i <= x1; i++)
        framebuffer[y * ST7789_WIDTH + i] = color;
}

void st7789_vline(int x, int y, int h, uint16_t color)
{
    if (x < 0 || x >= ST7789_WIDTH) return;
    int y1 = y + h - 1;
    if (y < 0) y = 0;
    if (y1 >= ST7789_HEIGHT) y1 = ST7789_HEIGHT - 1;
    for (int j = y; j <= y1; j++)
        framebuffer[j * ST7789_WIDTH + x] = color;
}

void st7789_fill_rect(int x, int y, int w, int h, uint16_t color)
{
    for (int j = y; j < y + h && j < ST7789_HEIGHT; j++)
        for (int i = x; i < x + w && i < ST7789_WIDTH; i++)
            if (i >= 0 && j >= 0)
                framebuffer[j * ST7789_WIDTH + i] = color;
}

void st7789_draw_char(int x, int y, char c, uint16_t color, int scale)
{
    uint8_t idx = (uint8_t)c;
    if (idx >= 128) return;
    const uint8_t *glyph = font8x8[idx];
    for (int row = 0; row < 8; row++) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                for (int sy = 0; sy < scale; sy++)
                    for (int sx = 0; sx < scale; sx++) {
                        int px = x + col * scale + sx;
                        int py = y + row * scale + sy;
                        if (px >= 0 && px < ST7789_WIDTH &&
                            py >= 0 && py < ST7789_HEIGHT)
                            framebuffer[py * ST7789_WIDTH + px] = color;
                    }
            }
        }
    }
}

void st7789_draw_string(int x, int y, const char *str, uint16_t color, int scale)
{
    int char_width = 8 * scale;
    while (*str) {
        if (x + char_width > ST7789_WIDTH)
            break;
        st7789_draw_char(x, y, *str, color, scale);
        x += char_width;
        str++;
    }
}

int st7789_string_width(const char *str, int scale)
{
    return (int)strlen(str) * 8 * scale;
}

void st7789_flush(void)
{
    if (spi_fd < 0) return;

    uint8_t ca[] = {0, 0, 0, ST7789_WIDTH - 1};
    tft_cmd_d(0x2A, ca, 4);
    uint8_t ra[] = {0, 0, 0, ST7789_HEIGHT - 1};
    tft_cmd_d(0x2B, ra, 4);
    tft_cmd(0x2C);
    tft_data((const uint8_t *)framebuffer, ST7789_WIDTH * ST7789_HEIGHT * 2);
}
